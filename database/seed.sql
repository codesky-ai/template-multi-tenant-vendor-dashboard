UPDATE suppliers s
SET
  total_orders = (
    SELECT COUNT(*)
    FROM orders o
    WHERE o.supplier_id = s.id
  ),
  total_value = (
    SELECT COALESCE(SUM(o.final_amount), 0)
    FROM orders o
    WHERE o.supplier_id = s.id
  ),
  last_activity_date = (
    SELECT MAX(o.order_date)
    FROM orders o
    WHERE o.supplier_id = s.id
  );

