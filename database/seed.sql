-- إحصائيات سريعة
SELECT
  'إحصائيات البيانات المُدرجة:' as section,
  (SELECT COUNT(*) FROM companies) as total_companies,
  (SELECT COUNT(*) FROM suppliers) as total_suppliers,
  (SELECT COUNT(*) FROM orders) as total_orders,
  (SELECT COUNT(*) FROM order_items) as total_order_items,
  (SELECT COUNT(*) FROM company_suppliers) as total_relationships,
  (SELECT COUNT(*) FROM users) as total_users;

-- عرض الموردين مع إحصائياتهم
SELECT
  '📊 إحصائيات الموردين:' as section,
  s.name as supplier_name,
  s.category,
  s.status,
  s.rating,
  s.total_orders,
  FORMAT(s.total_value, 2) as total_value_formatted
FROM suppliers s
ORDER BY s.total_value DESC
LIMIT 5;

-- عرض الطلبات الحديثة
SELECT
  '📋 آخر الطلبات:' as section,
  o.order_number,
  s.name as supplier_name,
  c.name as company_name,
  o.status,
  FORMAT(o.final_amount, 2) as amount,
  DATE_FORMAT(o.order_date, '%Y-%m-%d') as order_date
FROM orders o
JOIN suppliers s ON o.supplier_id = s.id
JOIN companies c ON o.company_id = c.id
ORDER BY o.order_date DESC
LIMIT 5;

-- عرض أفضل الفئات
SELECT
  '🏆 أفضل فئات الموردين:' as section,
  category,
  COUNT(*) as suppliers_count,
  AVG(rating) as avg_rating,
  SUM(total_value) as category_total_value
FROM suppliers
WHERE status = 'نشط'
GROUP BY category
ORDER BY category_total_value DESC;

